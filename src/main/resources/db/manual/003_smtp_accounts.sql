-- Preserve existing SMTP settings and allow multiple saved accounts.
BEGIN;
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = current_schema()
        AND table_name = 'email_settings' AND column_name = 'id' AND is_identity = 'NO' AND column_default IS NULL) THEN
        ALTER TABLE email_settings ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
        PERFORM setval(pg_get_serial_sequence('email_settings', 'id'), COALESCE((SELECT MAX(id) FROM email_settings), 1),
            EXISTS (SELECT 1 FROM email_settings));
    END IF;
END $$;
-- Guarantees one active sender, including under concurrent Admin requests.
CREATE UNIQUE INDEX IF NOT EXISTS idx_email_settings_single_active ON email_settings ((true)) WHERE enabled;
COMMIT;
